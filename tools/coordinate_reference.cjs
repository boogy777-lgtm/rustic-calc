// Development-only fixture generator. Pass a local official proj4.js 2.12.1
// distribution path. No npm install, no application runtime dependency.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const library = process.argv[2];
if (!library) throw Error('Usage: node tools/coordinate_reference.cjs <proj4.js path>');
const sha256 = crypto.createHash('sha256').update(fs.readFileSync(library)).digest('hex');
if (sha256 !== '9ecae61d88a976481c70d25069066205b10d541f098cdb69c02f3dd4dcac99cf') {
  throw Error('Unexpected reference library bytes');
}
const proj4 = require(path.resolve(library));
if (proj4.version !== '2.12.1') throw Error('Expected proj4.js 2.12.1');
const root = path.join(__dirname, '..');
const output = [
  '# Numerical reference fixtures generated by tools/coordinate_reference.cjs',
  '# proj4.js ' + proj4.version,
  '# Library SHA256: ' + sha256,
  '# Source: https://cdn.jsdelivr.net/npm/proj4@2.12.1/dist/proj4.js',
  '# Synthetic points test algorithms, NOT regional coverage or surveying accuracy.',
  '# template id\tlatitude\tlongitude\theight\tnorthing\teasting',
];
for (const line of fs.readFileSync(path.join(root, 'data/msk_templates.tsv'), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [id, , , definition] = line.split('\t');
  const lon0 = Number(definition.match(/\+lon_0=(\S+)/)[1]);
  for (const [lat, delta, height] of [[45, 0.75, 0], [60, -2.5, 150], [80, 6, 2000]]) {
    const lon = ((lon0 + delta + 180) % 360 + 360) % 360 - 180;
    const result = proj4('WGS84', definition, [lon, lat, height]);
    if (!result.every(Number.isFinite)) throw Error('Invalid reference for ' + id);
    output.push([id, lat, lon, height, result[1], result[0]].join('\t'));
  }
}
fs.writeFileSync(path.join(root, 'data/msk_reference.tsv'), output.join('\n') + '\n');
console.log('Generated ' + (output.length - 6) + ' numerical control points.');

const custom = output.slice(0, 6);
custom[5] = '# id\tPROJ definition\tlatitude\tlongitude\theight\tnorthing\teasting';
custom.splice(5, 0, '# For explicit zero shifts, reference adds an unknown datum name to avoid proj4.js PJD_NODATUM shortcut.');
for (const [id, definition, lat, lon, height] of [
  ['wgs84-origin-scale', '+proj=tmerc +lat_0=10 +lon_0=39 +k_0=0.9996 +x_0=500000 +y_0=-100 +datum=WGS84 +units=m +type=crs', 55.7558, 37.6173, 150],
  ['grs80-zero-shift', '+proj=tmerc +lat_0=0 +lon_0=15 +k=1 +x_0=0 +y_0=0 +ellps=GRS80 +towgs84=0,0,0 +units=m', -33.2, 16.5, -100],
  ['custom-three-dateline', '+proj=tmerc +lat_0=0 +lon_0=180.45 +k=1.00002 +x_0=10000 +y_0=-6000000 +a=6378245 +rf=298.3 +towgs84=23.57,-140.95,-79.8 +units=m', 66.9, -179, 1500],
  ['custom-seven-origin', '+proj=tmerc +lat_0=55.66666666667 +lon_0=37.5 +k=0.9987 +x_0=16.098 +y_0=14.512 +a=6377397.155 +rf=299.1528128 +towgs84=316.151,78.924,589.650,-1.57273,2.69209,2.34693,8.4507 +units=m', 55.8, 37.65, 1000],
  ['tm-domain-edge', '+proj=tmerc +lat_0=0 +lon_0=0 +k=1 +x_0=0 +y_0=0 +datum=WGS84 +units=m', 0, 30, 0],
  ['custom-ellipsoid-boundary', '+proj=tmerc +lat_0=89 +lon_0=0 +k=2 +x_0=1000000000 +y_0=-1000000000 +a=7000000 +rf=200 +towgs84=0,0,0 +units=m', -80, -29.5, 0],
]) {
  // proj4.js otherwise classifies an unnamed all-zero towgs84 as PJD_NODATUM,
  // bypassing even an explicit ellipsoid change. A non-built-in datum name
  // selects its zero-shift ECEF path without replacing a/rf/ellps or numbers.
  const referenceDefinition = /\+towgs84=0,0,0(?:\s|$)/.test(definition)
    ? definition + ' +datum=rustic_reference_zero' : definition;
  const result = proj4('WGS84', referenceDefinition, [lon, lat, height]);
  if (!result.every(Number.isFinite)) throw Error('Invalid reference for ' + id);
  custom.push([id, definition, lat, lon, height, result[1], result[0]].join('\t'));
}
fs.writeFileSync(path.join(root, 'data/custom_coordinate_reference.tsv'), custom.join('\n') + '\n');
console.log('Generated ' + (custom.length - 7) + ' custom-coordinate reference cases.');
