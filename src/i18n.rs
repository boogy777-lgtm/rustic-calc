//! Interface strings and display-name translations.

pub mod coordinates;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Ru,
    En,
}

impl Default for Lang {
    fn default() -> Self {
        Self::Ru
    }
}

impl Lang {
    pub fn text(self) -> &'static Text {
        match self {
            Self::Ru => &RU,
            Self::En => &EN,
        }
    }
}

#[cfg(test)]
mod branding_tests {
    use super::Lang;
    #[test]
    fn about_tracks_package_metadata_in_both_locales() {
        for lang in [Lang::Ru, Lang::En] {
            let text = lang.text();
            assert_eq!(text.app_title, "Rustic Calc");
            assert!(text.about_text.contains(env!("CARGO_PKG_VERSION")));
            assert!(text.about_text.contains(env!("CARGO_PKG_LICENSE")));
            assert!(text.about_text.contains(env!("CARGO_PKG_REPOSITORY")));
        }
    }
}

