/// Maps engine error strings that reach the display.
pub fn runtime_error(lang: Lang, text: &str) -> String {
    if lang == Lang::En {
        return text.to_string();
    }
    let t = lang.text();
    let translated = match text {
        "Invalid input" => t.error_invalid_input,
        "Result is undefined" => t.error_undefined,
        "Cannot divide by zero" => t.error_divide_zero,
        "Overflow" => t.error_overflow,
        "Unable to calculate" => t.error_unable,
        "Mismatched ')'" => "Лишняя скобка",
        "Date out of bound" => t.date_out_of_bound,
        "This value is not valid." => t.invalid_date,
        "This value cannot be blank." => "Заполните поле.",
        _ => return text.to_string(),
    };
    translated.to_string()
}

fn plural_ru(value: i32, one: &'static str, few: &'static str, many: &'static str) -> &'static str {
    let n = value.unsigned_abs() % 100;
    if (11..=14).contains(&n) {
        many
    } else {
        match n % 10 {
            1 => one,
            2..=4 => few,
            _ => many,
        }
    }
}

pub fn date_parts(lang: Lang, years: i32, months: i32, weeks: i32, days: i32) -> String {
    if years == 0 && months == 0 && weeks == 0 && days == 0 {
        return match lang {
            Lang::Ru => "Даты совпадают".to_string(),
            Lang::En => "Same dates".to_string(),
        };
    }
    let mut parts = Vec::new();
    let values = [
        (years, "year", "years", ("год", "года", "лет")),
        (months, "month", "months", ("месяц", "месяца", "месяцев")),
        (weeks, "week", "weeks", ("неделя", "недели", "недель")),
        (days, "day", "days", ("день", "дня", "дней")),
    ];
    for (value, en_one, en_many, ru) in values {
        if value == 0 {
            continue;
        }
        let label = match lang {
            Lang::Ru => plural_ru(value, ru.0, ru.1, ru.2),
            Lang::En => {
                if value == 1 {
                    en_one
                } else {
                    en_many
                }
            }
        };
        parts.push(format!("{value} {label}"));
    }
    parts.join(", ")
}
